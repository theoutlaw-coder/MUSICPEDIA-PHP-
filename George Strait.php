    <H2><B>George Strait</B></H2>
    <p>Pjevač George Strait jedan je od najprodavanijih country izvođača svih vremena, sa 60 pjesama na vrhu ljestvica i 31 albumom s platinastim ili multiplatinastim tiražom. Počeo je svirati u bendu dok je služio u američkoj vojsci. Strait je 1980-ih sklopio ugovor za snimanje s MCA Recordsom i producirao brojne hit albume tijekom sljedeća tri desetljeća. Poznat po tome što je ostao vjeran tradicionalnom country zvuku, osvojio je jednu Grammy i više drugih nagrada dok je sastavljao jedan od komercijalno najuspješnijih box setova u povijesti glazbe</p>
