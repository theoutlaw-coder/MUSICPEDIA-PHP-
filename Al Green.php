    <H2><B>Al Green</B></H2>
    <p>Kao tekstopisac i vokal, Al Green je preoblikovao zvuk soula, pružajući nezaboravne melodije intimnim, jednostavnim glasom koji pršti i duhovnom čežnjom i zemaljskom željom. Producent/suradnik Willie Mitchell i Green bili su pioniri u jednostavnom produkcijskom stilu s duvačkim instrumentima, neodoljivim ritmovima i gospel orguljama. Podjednako majstor zavođenja, tužaljke i slavlja, velečasni Green proširio je zvučne i emocionalne mogućnosti soula, popa i rocka.</p>
