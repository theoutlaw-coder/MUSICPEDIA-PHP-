    <p>Merle Haggard, uz vjerojatno iznimku Hanka Williamsa, stoji kao najutjecajniji kantautor u povijesti country glazbe. Bio je jedan od najsvestranijih umjetnika country glazbe, stilski je iskorištavao honky-tonk, blues, jazz, pop i folk. Haggardov repertoar bio je širok: bolne balade („Silver Wings“), lukave, razigrane naracije („It’s Been a Great Afternoon“), poluautobiografske refleksije („Mama Tried“), politički komentari („Rainbow Stew“), proleterske počasti („Workin’ Man Blues“) i pjesme za piće koje su standard za džuboks, cover bendove i za zatvaranje („I Think I’ll Just Stay Here and Drink“).</p>
