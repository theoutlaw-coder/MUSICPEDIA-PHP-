    <h2>Lil Wayne</h2>
    <p>Dwayne Michael Carter Jr. (rođen 27. rujna 1982.), profesionalno poznat kao Lil Wayne, američki je reper, pjevač, tekstopisac i izvršni direktor diskografske kuće. Općenito se smatra jednim od najutjecajnijih hip hop umjetnika svoje generacije i često se navodi kao jedan od najvećih repera svih vremena. Njegova karijera započela je 1995. godine, u dobi od 12 godina, kada ga je potpisao reper Birdman, pridruživši se Cash Money Recordsu kao najmlađi član izdavačke kuće. Od tada je Wayne bio vodeći umjetnik Cash Money Recordsa prije nego što je prekinuo suradnju s tvrtkom u lipnju 2018.</p>
