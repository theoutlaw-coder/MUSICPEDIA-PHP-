    <H2><B>Beyonce</B></H2>
    <p>Beyonce Knowles rođena je i odrasla u Houstonu. Rođendan joj je 4. rujna 1981., a visoka je 177 cm. Počela je s djevojačkom grupom Destiny's Child, koja je stekla slavu pjesmom "No, No, No" 1997. i drugim albumom 'The Writing's on the Wall' 1999. Queen Bey objavila je svoj solo album 'Dangerously in Love' 2003. Debitirao je na prvom mjestu Billboard 200 ljestvice od 12. srpnja 2003. "Crazy in Love" bio je prvi singl s albuma, a na njemu je bio Jay-Z (za kojeg će se zvijezda udati 2008.); pjesma je osam tjedana bila na vrhu Hot 100 ljestvice. U veljači 2023. Beyonce je postala najveća dobitnica Grammyja svih vremena, prekinuvši izjednačenje s pokojnim klasičnim dirigentom Sir Georgom Soltijem, kada je svoj ukupan broj nagrada dovela do 32, koje će nastaviti dodavati u godinama koje su uslijedile. Godine 2025. konačno je osvojila nagradu za album godine, ponijevši kući nagradu za LP broj 1 iz 2024. 'Cowboy Carter'. Te je godine okrunjena za najveću pop zvijezdu Billboarda 21. stoljeća.</p>
