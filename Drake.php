    <h2><b>Drake</b></h2>
    <p>Aubrey Drake Graham rođen je u Torontu, Ontario, kao sin Dennisa Grahama, glazbenika rođenog u Memphisu, Tennessee, i Sandi (Sher) Graham, kanadske prosvjetne djelatnice. Kao mladić, Drake se pojavio u nekoliko reklama za trgovce poput Searsa i GMC-a. Godine 2001. Drake se proslavio ulogom "Jimmyja Brooksa", lika u seriji Degrassi: Novi naraštaj (2001.), košarkaške zvijezde koja je vezana za invalidska kolica nakon što ju je upucao kolega iz razreda. Godine 2006. Drake je započeo svoju glazbenu karijeru objavljivanjem svog prvog mixtapea "Room for Improvement". Tri godine kasnije, njegov treći mixtape "So Far Gone" donio mu je kritički i komercijalni uspjeh, a sljedeće godine objavio je svoj službeni debitantski album "Thank Me Later", koji je uglavnom dobio pozitivne kritike. Aubrey Drake Graham etablirao se kao multitalentirani mladi Kanađanin, a industrija zabave ima velika očekivanja od njega.</p>
