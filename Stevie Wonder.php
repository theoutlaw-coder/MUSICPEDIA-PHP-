    <p>Stevie Wonder je glazbeni genij koji je redefinirao pop, R&B i soul koristeći sintisajzere i inovativne ritmove. Slijep od djetinjstva, Stevie je već kao tinejdžer postao zvijezda Motowna, da bi u 70-ima stvorio niz kultnih albuma koji su osvajali Grammyje jedan za drugim. Njegova glazba nosi snažne poruke ljubavi i društvene pravde, a njegova virtuoznost na klavijaturama i usnoj harmonici ostaje bez premca.</p>
