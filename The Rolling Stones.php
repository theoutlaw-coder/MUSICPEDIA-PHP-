    <h2>The Rolling Stones:</h2>
    <p>The Rolling Stones su sinonim za dugovječnost i čisti rock and roll duh. Od svojih početaka kao buntovni odgovor na Beatlese, Stonesi su spojili sirovi blues s pop senzibilitetom, stvarajući zvuk koji je definirao "opasnu" stranu rocka. Predvođeni neuništivim dvojcem Jagger-Richards, postali su najveći koncertni spektakl na svijetu. Njihova sposobnost da prežive desetljeća mijenjajući se kroz psihodeliju, disco i punk, dok istovremeno zadržavaju svoj prepoznatljivi "groove", osigurala im je titulu najvećeg rock benda na svijetu.</p>
