    <h2>Kendrick Lamar</h2>
    <p>Kendrick Lamar (rođen 17. lipnja 1987., Compton, Kalifornija, SAD) je američki reper koji je postigao kritički i komercijalni uspjeh albumima kao što su good kid, m.A.A.d city (2012.) i To Pimp a Butterfly (2015.) te singlovima kao što je “Not Like Us” (2024.). Smatran jednim od najboljih tekstopisaca svoje generacije, 2018. godine postao je prvi neklasični ili jazz izvođač koji je osvojio Pulitzerovu nagradu za glazbu. Dvije godine nakon izlaska albuma GNX 2024. godine, oborio je rekord za najviše osvojenih Grammy nagrada od strane repera, osvojivši 27 Grammyja.</p>
