    <h2><b>Bobby McFerrin</b></h2>
    <p>Bobby McFerrin (rođen 11. ožujka 1950., Manhattan, New York, SAD) je američki glazbenik poznat po svojoj iznimnoj vokalnoj kontroli i improvizacijskim sposobnostima. Često pjeva a cappella, miješajući narodne pjesme, rock i soul melodije iz 1960-ih i jazz teme s originalnim tekstovima. Najradije pjeva bez fiksnih tekstova i može s velikom vještinom oponašati zvukove raznih glazbenih instrumenata.</p>
