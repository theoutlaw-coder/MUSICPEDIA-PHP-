    <h2><b>Ella Fitzgerald</b></h2>
    <p>Nazvana „Prvom damom pjesme“, Ella Fitzgerald bila je najpopularnija jazz pjevačica u Sjedinjenim Državama više od pola stoljeća. Za života je osvojila 13 nagrada Grammy i prodala preko 40 milijuna albuma.

Njezin glas bio je fleksibilan, širokog raspona, precizan i bezvremenski. Mogla je pjevati zavodljive balade, slatki jazz i imitirati svaki instrument u orkestru. Radila je sa svim jazz velikanima, od Dukea Ellingtona, Counta Basieja i Nata King Colea, do Franka Sinatre, Dizzyja Gillespieja i Bennyja Goodmana. (Ili bi bolje rečeno, neki rekli da su svi jazz velikani imali zadovoljstvo raditi s Ellom.)

Nastupala je na vrhunskim mjestima diljem svijeta i punila ih do daske. Njezina publika bila je raznolika kao i njezin vokalni raspon. Bili su bogati i siromašni, sastavljena od svih rasa, svih religija i svih nacionalnosti. Zapravo, mnogi od njih imali su samo jedan zajednički faktor - svi su je voljeli.</p>
