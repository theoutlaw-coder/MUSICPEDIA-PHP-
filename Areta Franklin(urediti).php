    <p>Aretha Franklin (rođena 25. ožujka 1942., Memphis, Tennessee, SAD - umrla 16. kolovoza 2018., Detroit, Michigan) bila je američka pjevačica koja je definirala zlatno doba soul glazbe 1960-ih. Smatrana jednom od najvećih vokalistica 20. stoljeća, Franklin je posjedovala impresivan gospel glas kojim je vladala nizom glazbenih stilova, uključujući jazz, blues, pop, rhythm and blues (R&B), rock, pa čak i operu.</p>
