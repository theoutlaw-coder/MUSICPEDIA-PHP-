    <H2>Nicki Minaj</H2>
    <p>Nicki Minaj rođena je kao Onika Tanya Maraj 8. prosinca 1982. u St. Jamesu, Port of Spain, Trinidad i Tobago, a odrasla je u Queensu, New York City, New York. Odrasla je u problematičnoj obitelji s ocem koji je bio ovisnik o drogama, a kasnije se promijenio nakon što se prijavio na rehabilitaciju i počeo ići u crkvu. Minaj je pohađala srednju školu LaGaurdia i studirala pjevanje i glumu.

Prvi ju je primijetio izvršni direktor Young Moneyja, a kasnije je regrutirana za Carter Edition vlastite DVD serije Young Moneyja "The Come Up". Njezine reperske vještine privukle su pozornost Lil Waynea koji je kasnije surađivao s njom na mnogim suradnjama s njegovim mixtapeovima.

U travnju 2007. Minaj je objavila svoj prvi mixtape "Playtime Is Over". Godinu dana kasnije snimila je još jedan mixtape "Sucka Free" koji ju je proglasio izvođačicom godine na dodjeli nagrada Underground Music Awards. Godine 2009. snimila je svoj treći mixtape "Beam Me Up Scotty" koji je dobio pozitivne kritike od BET-a i MTV-a.</p>
